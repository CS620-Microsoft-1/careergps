"""Rebuild the generated tables in REPORT.md from results.csv.

Only the part between the RESULTS markers is replaced, so notes written elsewhere in the
report survive. Statistics are computed here in Python, never by a model.

    python -m experiments.skill_gap_latency.summarize
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from statistics import mean, median

from .run import CONFIGS, FAMILIES, LEVELS, RESULTS

REPORT = Path(__file__).resolve().parent / "REPORT.md"
START, END = "<!-- RESULTS:START (generated by summarize.py; do not edit) -->", "<!-- RESULTS:END -->"
ROLE_NAMES = {"software_engineer": "Software Engineer", "data_analyst": "Data Analyst", "ai_engineer": "AI Engineer"}
PLANNED = {
    **CONFIGS,
    "B": "Single Agent, low reasoning (1 call)",
    "D": "3 smaller Agents in parallel, low reasoning",
}
GROUPS = ("foundation", "lifecycle", "systems")


def read_rows(path=RESULTS):
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def number(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def stats(rows, field):
    values = [value for value in (number(row.get(field)) for row in rows) if value is not None]
    if not values:
        return None
    return {"mean": mean(values), "median": median(values), "min": min(values), "max": max(values), "n": len(values)}


def agreement(rows):
    """Share of skills with the same verdict (and the same verdict + activity) in every repeat."""
    runs = [json.loads(row["verdicts"]) for row in rows if row.get("status") == "ok" and row.get("verdicts")]
    if len(runs) < 2:
        return None, None
    skills = set().union(*runs)
    same_verdict = sum(len({tuple(run.get(skill) or [None, None])[0] for run in runs}) == 1 for skill in skills)
    same_activity = sum(len({tuple(run.get(skill) or [None, None]) for run in runs}) == 1 for skill in skills)
    return same_verdict / len(skills), same_activity / len(skills)


def mean_agreement(rows):
    """Agreement only compares repeats of one résumé, so a group averages its résumés' values."""
    pairs = [agreement([row for row in rows if row["resume"] == name]) for name in sorted({row["resume"] for row in rows})]
    verdicts = [verdict for verdict, _ in pairs if verdict is not None]
    activities = [activity for _, activity in pairs if activity is not None]
    return (mean(verdicts) if verdicts else None), (mean(activities) if activities else None)


def _s(value, digits=1):
    return "–" if value is None else f"{value:.{digits}f}"


def _tokens(value):
    return "–" if value is None else f"{value:,.0f}"


def _pct(value):
    return "–" if value is None else f"{value:.0%}"


def group_row(label, rows):
    ok = [row for row in rows if row.get("status") == "ok"]
    total, inference = stats(ok, "total_s"), stats(ok, "inference_s")
    verdict, activity = mean_agreement(rows)
    tokens = {field: (stats(ok, field) or {}).get("mean")
              for field in ("input_tokens", "cached_tokens", "output_tokens", "reasoning_tokens")}
    errors = (stats(ok, "reference_errors") or {}).get("mean")
    return (f"| {label} | {len(ok)}/{len(rows)} | {_s((total or {}).get('mean'))} | {_s((total or {}).get('min'))} | "
            f"{_s((total or {}).get('max'))} | {_s((inference or {}).get('mean'))} | {_tokens(tokens['input_tokens'])} | "
            f"{_tokens(tokens['cached_tokens'])} | {_tokens(tokens['output_tokens'])} | {_tokens(tokens['reasoning_tokens'])} | "
            f"{_pct(verdict)} | {_pct(activity)} | {_s(errors)} |")


GROUP_HEADER = ("| {0} | Runs OK | Mean total (s) | Fastest (s) | Slowest (s) | Mean model call (s) | Input tok | "
                "Cached tok | Output tok | Reasoning tok | Same verdict | Same verdict + activity | Invalid quotes / run |\n"
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|")


def config_section(config, rows):
    ok = [row for row in rows if row.get("status") == "ok"]
    versions = sorted({row["agent_version"] for row in rows if row.get("agent_version")})
    models = sorted({f"{row['model']} / {row['reasoning_effort']}" for row in rows if row.get("model")})
    dates = sorted(row["started_at"] for row in rows)
    phases = {field: (stats(ok, field) or {}).get("mean")
              for field in ("prepare_s", "setup_s", "conversation_s", "inference_s", "scoring_s", "total_s")}
    lines = [
        f"### Config {config}: {PLANNED.get(config, CONFIGS.get(config, ''))}", "",
        f"- Agent: {', '.join(sorted({row['agent_name'] for row in rows if row.get('agent_name')})) or '–'}, "
        f"version {', '.join(versions) or '–'}; model / reasoning: {', '.join(models) or '–'}",
        f"- Runs: {len(rows)} ({len(rows) - len(ok)} failed), "
        f"{dates[0][:16].replace('T', ' ')} to {dates[-1][:16].replace('T', ' ')} UTC",
        "",
        "**Where the time goes (mean seconds per run, successful runs)**", "",
        "| Prepare input | Auth + Agent check | Conversation create/delete | Model call | Scoring | Total |",
        "|---|---|---|---|---|---|",
        "| " + " | ".join(_s(phases[field], 2) for field in
                         ("prepare_s", "setup_s", "conversation_s", "inference_s", "scoring_s", "total_s")) + " |",
        "", "**By résumé**", "", GROUP_HEADER.format("Résumé"),
    ]
    for role in FAMILIES:
        for level in LEVELS:
            name = f"{role}_{level}"
            subset = [row for row in rows if row["resume"] == name]
            if subset:
                lines.append(group_row(name, subset))
    lines += ["", "**By role**", "", GROUP_HEADER.format("Role")]
    for family, label in ROLE_NAMES.items():
        subset = [row for row in rows if row["role"] == family]
        if subset:
            lines.append(group_row(label, subset))
    lines += ["", "**By résumé level**", "", GROUP_HEADER.format("Level")]
    for level in LEVELS:
        subset = [row for row in rows if row["level"] == level]
        if subset:
            lines.append(group_row(level, subset))
    lines += ["", "**All runs**", "", GROUP_HEADER.format("Config"), group_row(config, rows)]
    if any(row.get("group_inference_s") for row in ok):
        lines += ["", *group_section(ok)]
    failed = [row for row in rows if row.get("status") != "ok"]
    if failed:
        lines += ["", "**Failures**", ""] + [f"- {row['resume']} r{row['round']}: {row['error']}" for row in failed]
    return "\n".join(lines)


def group_section(ok):
    """Per skill-group Agent: its own model-call time, output size, and how often it finished last."""
    lines = ["**By skill-group Agent (3 parallel calls; the run waits for the slowest)**", "",
             "| Group | Mean model call (s) | Fastest (s) | Slowest (s) | Mean output tok | Slowest in run |",
             "|---|---|---|---|---|---|"]
    for group in GROUPS:
        calls = [{"x": json.loads(row["group_inference_s"]).get(group)} for row in ok if row.get("group_inference_s")]
        tokens = [{"x": json.loads(row["group_output_tokens"]).get(group)} for row in ok if row.get("group_output_tokens")]
        call, out = stats(calls, "x") or {}, stats(tokens, "x") or {}
        last = sum(row.get("slowest_group") == group for row in ok)
        lines.append(f"| {group} | {_s(call.get('mean'))} | {_s(call.get('min'))} | {_s(call.get('max'))} | "
                     f"{_tokens(out.get('mean'))} | {last}/{len(ok)} |")
    blocked = (stats(ok, "review_blocked") or {}).get("mean")
    lines += ["", f"Skills the merge set to *uncertain* because the owning group's evidence failed the quote checks: "
                  f"{_s(blocked)} per run on average (these count as uncertain, not as invalid quotes)."]
    return lines


def _change(total, base):
    return f"{(total['mean'] / base['mean'] - 1):+.0%}" if base and total else "–"


def comparison(by_config):
    def base(config):
        return stats([row for row in by_config.get(config, []) if row.get("status") == "ok"], "total_s")

    lines = ["| Config | Setup | Runs OK | Mean total (s) | Median (s) | Fastest (s) | Slowest (s) | "
             "Mean output tok | Same verdict | Change vs A | Change vs A6 |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for config, label in PLANNED.items():
        rows = by_config.get(config, [])
        if not rows:
            lines.append(f"| {config} | {label} | not run yet | – | – | – | – | – | – | – | – |")
            continue
        ok = [row for row in rows if row.get("status") == "ok"]
        total = stats(ok, "total_s") or {}
        output = (stats(ok, "output_tokens") or {}).get("mean")
        vs_a = "baseline" if config == "A" else _change(total, base("A"))
        vs_a6 = "–" if config in ("A", "A6") else _change(total, base("A6"))
        lines.append(f"| {config} | {label} | {len(ok)}/{len(rows)} | {_s(total.get('mean'))} | {_s(total.get('median'))} | "
                     f"{_s(total.get('min'))} | {_s(total.get('max'))} | {_tokens(output)} | "
                     f"{_pct(mean_agreement(rows)[0])} | {vs_a} | {vs_a6} |")
    return "\n".join(lines)


def build(rows):
    by_config = {}
    for row in rows:
        by_config.setdefault(row["config"], []).append(row)
    parts = [START, "", "## Results", "", "### Comparison", "", comparison(by_config)]
    for config in sorted(by_config, key=lambda name: (list(PLANNED).index(name) if name in PLANNED else 99, name)):
        parts += ["", config_section(config, by_config[config])]
    parts += ["", END]
    return "\n".join(parts)


def write_report(rows, report=REPORT):
    generated = build(rows)
    text = report.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{report} has no RESULTS markers; add them where the tables should go.")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    report.write_text(head + generated + tail, encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=RESULTS)
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    rows = read_rows(args.results)
    write_report(rows, args.report)
    print(f"{args.report}: {len(rows)} runs summarized.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
